#!/usr/bin/env python3
"""Import build-pinned OnEquip effects; never invent scores for triggered effects."""
import argparse
import csv
import hashlib
import io
import json
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
BUILD = '1.60.1.70862'
PINS = {
    'ItemEffect': 'df9f123861be4e180736e79dcee708151c6f79de9f5e6773ff8e2066430aa434',
    'ItemXItemEffect': '15dc36eec90ca5768e00469cb8065aedf82efcf205ca03281daf6aac69ca1885',
    'SpellEffect': 'cc8f167fe246b495294b560196f6c59439f703e8f937ddb6acd81157bd5f8b9c',
}


def read(name):
    raw = (ROOT / f'.dependencies/{name}-{BUILD}-zhCN.csv').read_bytes()
    assert hashlib.sha256(raw).hexdigest() == PINS[name], name
    rows = {}
    for row in csv.DictReader(io.StringIO(raw.decode('utf-8-sig'))):
        ident = int(row['ID'])
        assert ident > 0 and ident not in rows and None not in row
        assert all(v is not None for v in row.values())
        rows[ident] = row
    return rows


def flat_stats(effect, rows):
    # Only constant self auras can be checked against GetItemStats. Other effects remain qualitative.
    if not rows or int(effect['ChrSpecializationID']) or int(effect['PlayerConditionID']):
        return None
    result = defaultdict(float)
    zero = ['DifficultyID', 'EffectAttributes', 'EffectTriggerSpell', 'EffectAuraPeriod',
            'EffectRealPointsPerLevel', 'EffectPointsPerResource', 'EffectBonusCoefficient',
            'BonusCoefficientFromAP', 'Coefficient', 'Variance', 'ResourceCoefficient',
            'ScalingClass', 'ImplicitTarget_1', 'EffectMiscValue_1', 'EffectRadiusIndex_0',
            'EffectRadiusIndex_1', 'EffectChainTargets', 'EffectMechanic']
    zero += [f'EffectSpellClassMask_{i}' for i in range(4)]
    for row in rows:
        if int(row['Effect']) != 6 or int(row['ImplicitTarget_0']) != 1 or any(float(row[k]) for k in zero):
            return None
        aura, misc, amount = int(row['EffectAura']), int(row['EffectMiscValue_0']), float(row['EffectBasePointsF'])
        if amount <= 0:
            return None
        if aura == 29 and 0 <= misc <= 4:
            stat = ['STRENGTH', 'AGILITY', 'STAMINA', 'INTELLECT', 'SPIRIT'][misc]
        elif aura in (99, 124) and misc == 0:
            stat = 'ATTACK_POWER' if aura == 99 else 'RANGED_ATTACK_POWER'
        elif aura in (13, 135) and misc == 126:
            stat = 'SPELL_DAMAGE_DONE' if aura == 13 else 'SPELL_HEALING_DONE'
        else:
            return None
        result[stat] += amount
    return dict(result)


def build():
    effects, links, spells = [read(n) for n in PINS]
    spell_rows = defaultdict(list)
    for row in spells.values():
        spell_rows[int(row['SpellID'])].append(row)
    items, missing, missing_spells = {}, [], set()
    for link in sorted(links.values(), key=lambda r: int(r['ID'])):
        ident = int(link['ItemID'])
        assert ident > 0
        effect = effects.get(int(link['ItemEffectID']))
        if effect and int(effect['TriggerType']) != 1:
            continue
        item = items.setdefault(ident, dict(spells=[], stats={}, complex=False))
        if not effect:
            missing.append(link);item['complex'] = True
            continue
        spell = int(effect['SpellID'])
        assert spell > 0
        if int(effect['ChrSpecializationID']) or int(effect['PlayerConditionID']):
            item['conditional'] = True
            item['complex'] = True
        if spell in item['spells']:
            continue
        item['spells'].append(spell)
        rows = spell_rows[spell]
        if not rows:
            missing_spells.add(spell)
        flat = flat_stats(effect, rows)
        if flat is None:
            item['complex'] = True
        else:
            for stat, value in flat.items():
                item['stats'][stat] = item['stats'].get(stat, 0) + value
    lines = ['local _,A=...', '-- Generated by tools/import_item_effects.py; see docs/ITEM_EFFECT_AUDIT.json.',
             'A.ItemEffects={version="1.60.1",build="70862",interface=16001,clientVerified=false,items={']
    for ident, item in sorted(items.items()):
        parts = ['spells={' + ','.join(str(n) for n in item['spells']) + '}']
        if item.get('conditional'):
            parts.append('conditional=true')
        if item['complex']:
            parts.append('complex=true')
        else:
            parts.append('stats={' + ','.join(f'{k}={v:g}' for k, v in sorted(item['stats'].items())) + '}')
        lines.append(f'    [{ident}]={{' + ','.join(parts) + '},')
    lines += ['}}', '']
    report = dict(build=BUILD, clientVerified=False,
        sources=[dict(table=n, sha256=h, url=f'https://wago.tools/db2/{n}/csv?build={BUILD}&locale=zhCN') for n, h in PINS.items()],
        counts=dict(items=len(items), complexItems=sum(v['complex'] for v in items.values()),
                    flatCandidates=sum(not v['complex'] for v in items.values()), missingEffects=len(missing), missingSpells=len(missing_spells)),
        missingEffects=missing, missingSpellIds=sorted(missing_spells),
        policy='OnEquip only. Exact client build required. Constant self stat auras are considered covered only when live GetItemStats contains their complete totals. All other effects are qualitative; never added to attribute scores.',
        items=items)
    return '\n'.join(lines), report


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    lua, report = build()
    for name, value in {'Data/ItemEffects.lua': lua, 'docs/ITEM_EFFECT_AUDIT.json': json.dumps(report, ensure_ascii=False, indent=2)+'\n'}.items():
        path = ROOT / name
        if args.check:
            assert path.read_text() == value, name
        else:
            path.write_text(value)
    print(json.dumps(report['counts']))


if __name__ == '__main__':
    main()
