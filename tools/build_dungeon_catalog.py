#!/usr/bin/env python3
"""Build a task reference catalogue, separate from executable dungeon itineraries."""
import argparse
import csv
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def render():
    census = json.loads((ROOT / 'docs/DUNGEON_COVERAGE.json').read_text())
    evidence = json.loads((ROOT / 'docs/DUNGEON_QUEST_LOCATIONS.json').read_text())
    preparation = {row['mapId']: row.get('preparationQuests', {})
                   for row in census['announcedLevelingDungeons']['entries'] if row['mapId']}
    datasets = {}
    for ds in evidence['datasets']:
        for faction, _ in ds['personas']:
            assert faction not in datasets or datasets[faction] == ds, 'class-dependent evidence needs separate catalogue entries'
            datasets[faction] = ds
    lines = ['-- Generated by tools/build_dungeon_catalog.py; task references, not verified itineraries.',
             '-- Sources: docs/DUNGEON_COVERAGE.json and docs/DUNGEON_QUEST_LOCATIONS.json.',
             'local _,A=...', 'A.DungeonCatalog={version="1.60.1",build="70862",entries={']
    for m in census['maps']:
        if m['classification'] != 'party':
            continue
        areas = ','.join(str(area) for area in m['aliases'])
        entrances = ','.join('{'+','.join(str(value) for value in point)+'}' for point in m['entrances'])
        lines.append(f'    ["reference:{m["mapId"]}"]={{id="reference:{m["mapId"]}",reference=true,instanceId={m["mapId"]},title={json.dumps(m["name"],ensure_ascii=False)},areas={{{areas}}},entrances={{{entrances}}},quests={{')
        for faction, ds in sorted(datasets.items()):
            refs = {qid: 'category' for qid in m['categoryQuestIds']}
            for target in ds['targets']:
                if target['phase'] != 'objective':
                    continue
                rows = target['sources']
                inside = any(m['mapId'] in row['instanceMapIds'] for row in rows)
                other = any(m['mapId'] not in row['instanceMapIds'] for row in rows)
                qid = target['questId']
                if inside and not other:
                    refs[qid] = 'inside'
                elif inside and qid in refs and refs[qid] != 'inside' and any(row['areaId'] > 0 and m['mapId'] not in row['instanceMapIds'] for row in rows):
                    refs[qid] = 'alternative'
            for qid in preparation.get(m['mapId'], {}).get(faction, []):
                refs[qid] = 'preparation'
            pairs = ','.join(f'[{qid}]="{kind}"' for qid, kind in sorted(refs.items()))
            lines.append(f'        {faction}={{{pairs}}},')
        lines.append('    }},')
    lines.append('}}')
    encounters = ROOT / '.dependencies/DungeonEncounter-1.60.1.70862-zhCN.csv'
    assert hashlib.sha256(encounters.read_bytes()).hexdigest() == '13c1a984836ccd90fc0adb56d7a52aeacab794b7276e836f30e18a80725e8677'
    party_maps = {m['mapId'] for m in census['maps'] if m['classification'] == 'party'}
    rows = sorted(csv.DictReader(encounters.open()), key=lambda r: int(r['ID']))
    assert len({r['ID'] for r in rows}) == len(rows)
    lines.append('-- Encounter identities only; optional bosses and separate wings are not completion requirements.')
    lines.append('A.DungeonCatalog.encounters={')
    for row in rows:
        if int(row['MapID']) not in party_maps:
            continue
        title = json.dumps(row['Name_lang'], ensure_ascii=False)
        lines.append(f'    [{row["ID"]}]={{instanceId={row["MapID"]},difficultyId={row["DifficultyID"]},title={title}}},')
    lines.append('}')
    loot_path = ROOT / '.dependencies/eg-link-156f29c9/1.60.1.70862/loot.json'
    assert hashlib.sha256(loot_path.read_bytes()).hexdigest() == 'fc1308917a42b0518778df0e0bbcfb46847addb4e1db45c2c3e47514081a2675'
    loot = json.loads(loot_path.read_text())
    assert loot['format'] == 3 and loot['meta']['clientBuild'] == '1.60.1.70862'
    identities = {int(row['ID']): row for row in rows if int(row['MapID']) in party_maps}
    names = {m['mapId']: m['name'] for m in census['maps']}
    drops = {}
    for key, record in loot['rolls'].items():
        encounter = int(key.split('|')[0].removeprefix('encounter:'))
        identity = identities.get(encounter)
        if not identity or record['kills'] <= 0:
            continue
        instance = int(identity['MapID'])
        for item, observation in record['items'].items():
            assert int(item) > 0 and observation['drops'] > 0
            source = f'drop:{encounter}:{item}'
            drops[source] = (instance, encounter, int(item), identity['Name_lang'])
    assert len(drops) == 11
    lines.append('-- Efficient Games CC BY 4.0: observed roll sources, not drop or allocation probabilities.')
    lines.append('A.DungeonCatalog.loot={')
    for key, (instance, encounter, item, boss) in sorted(drops.items()):
        title = json.dumps(names[instance] + ' · ' + boss, ensure_ascii=False)
        lines.append(f'    ["{key}"]={{id="{key}",reference=true,kind="dungeon",dungeonId="reference:{instance}",instanceId={instance},encounterId={encounter},itemId={item},title={title}}},')
    lines.append('}')
    assignments = ROOT / '.dependencies/UiMapAssignment-1.60.1.70862.csv'
    assert hashlib.sha256(assignments.read_bytes()).hexdigest() == '79267e8be8034e47daab14350411b3acc0b1f64e86efc9d821a217497254ca0a'
    maps = list(csv.DictReader(assignments.open()))
    lines.append('A.PvPCatalog={version="1.60.1",build="70862",entries={')
    for m in census['maps']:
        if m['classification'] != 'battleground':
            continue
        ui_maps = sorted({int(r['UiMapID']) for r in maps if int(r['MapID']) == m['mapId']})
        areas = ','.join(str(area) for area in m['aliases'])
        ui = ','.join(str(mid) for mid in ui_maps)
        lines.append(f'    [{m["mapId"]}]={{instanceId={m["mapId"]},title={json.dumps(m["name"],ensure_ascii=False)},areas={{{areas}}},maps={{{ui}}}}},')
    lines.append('}}')
    return '\n'.join(lines) + '\n'


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    path = ROOT / 'Data/Dungeons.lua'
    text = render()
    if args.check:
        assert path.read_text() == text
    else:
        path.write_text(text)
    print('Dungeon task catalogue:', len(text.encode()), 'bytes')
