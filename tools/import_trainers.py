#!/usr/bin/env python3
"""Derive trainer relevance from pinned native offerings and same-build skill rows."""
import argparse
import csv
import hashlib
import json
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
BUILD = '1.60.1.70862'
REV = '156f29c9af78b1586883e8eb94a13467eb89638c'
TRAINERS = f'eg-link-{REV[:8]}/{BUILD}/trainers.json'
PINS = {
    TRAINERS: '549ff046e68fdcfea175313d3cfbdfaa5a60ac809608779c79e326d83eb189e7',
    f'SkillLine-{BUILD}-zhCN.csv': 'db0fe59fc385e1b3c25528f0504430631fc592de564840dc601a428c2ec646a4',
    f'SkillLineAbility-{BUILD}-zhCN.csv': '13ef58a08253125e3e9dca642a39bc480187987e90cfbe5c8be30e1ab3c8be0a',
}


def classify(trainer, abilities, skills):
    classes, professions, missing = set(), set(), []
    for key, service in trainer['services'].items():
        spell = int(key)
        assert spell > 0 and service['spellId'] == spell
        rows = abilities.get(spell, [])
        if not rows:
            missing.append(spell)
        for row in rows:
            skill = skills.get(int(row['SkillLine']))
            if not skill:
                missing.append(spell)
                continue
            category, mask = int(skill['CategoryID']), int(row['ClassMask'])
            if category == 7 and mask:
                classes.add(mask)
            if category in (9, 11):
                professions.add(int(skill['ID']))
    result = {}
    # Partial observations establish relevance, never exclusivity or learnability.
    if not missing and trainer['trainerType'] == 0 and not trainer['tradeskill'] and len(classes) == 1:
        mask = next(iter(classes))
        if mask > 0 and mask & (mask - 1) == 0:
            result['classMask'] = mask
    if not missing and trainer['trainerType'] == 2 and trainer['tradeskill'] and len(professions) == 1:
        result['skill'] = next(iter(professions))
    return result, sorted(set(missing))


def generate():
    dep = ROOT / '.dependencies'
    for name, digest in PINS.items():
        assert hashlib.sha256((dep / name).read_bytes()).hexdigest() == digest, name
    data = json.loads((dep / TRAINERS).read_text())
    meta = data['meta']
    assert (meta['clientBuild'], meta['product'], meta['schemaVersion'], meta['license']) == (BUILD, 'wowf', 1, 'CC BY 4.0')
    skills = {int(r['ID']): r for r in csv.DictReader((dep / f'SkillLine-{BUILD}-zhCN.csv').open())}
    abilities = defaultdict(list)
    for row in csv.DictReader((dep / f'SkillLineAbility-{BUILD}-zhCN.csv').open()):
        abilities[int(row['Spell'])].append(row)
    profiles, gaps = {}, {}
    for key, trainer in sorted(data['trainers'].items(), key=lambda pair: int(pair[0])):
        profile, missing = classify(trainer, abilities, skills)
        profiles[int(key)] = profile
        if missing:
            gaps[key] = missing
    skill_ids = sorted({p['skill'] for p in profiles.values() if 'skill' in p})
    lines = ['-- Generated by tools/import_trainers.py; observed offerings are partial.',
             '-- Data from Efficient Games (https://efficient.games), CC BY 4.0.',
             'local _,A=...', 'A.Trainers={version="1.60.1",build="70862",interface=16001,skills={']
    for skill in skill_ids:
        lines.append(f'    [{skill}]={json.dumps(skills[skill]["DisplayName_lang"], ensure_ascii=False)},')
    lines.append('},npcs={')
    for npc, profile in profiles.items():
        fields = ','.join(f'{key}={value}' for key, value in sorted(profile.items()))
        lines.append(f'    [{npc}]={{{fields}}},')
    lines.append('}}')
    audit = {'build': BUILD, 'clientVerified': False, 'attribution': meta['attribution'],
             'inputs': PINS, 'source': f'https://raw.githubusercontent.com/JIVESCORP/eg-link-output-wowf/{REV}/data/wowf/{BUILD}/trainers.json',
             'counts': {'observedTrainers': len(profiles), 'classProfiles': sum('classMask' in p for p in profiles.values()),
                        'professionProfiles': sum('skill' in p for p in profiles.values()), 'skills': len(skill_ids)},
             'profiles': profiles, 'missingSpellLinks': gaps,
             'scope': 'Relevance ordering only. Partial offerings do not prove exclusive class access, available training, costs or training benefits.'}
    return '\n'.join(lines) + '\n', json.dumps(audit, ensure_ascii=False, indent=2) + '\n'


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    for name, content in zip(['Data/Trainers.lua', 'docs/TRAINER_DATA_AUDIT.json'], generate()):
        path = ROOT / name
        if args.check:
            assert path.read_text() == content, name
        else:
            with path.open('x') as output:
                output.write(content)
    print('Trainer relevance data verified' if args.check else 'Trainer relevance data generated')


if __name__ == '__main__':
    main()
