#!/usr/bin/env python3
"""Import build-pinned set membership and bonus thresholds, preserving conflicts."""
import argparse
import csv
import hashlib
import io
import json
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
BUILD = '1.60.1.70862'
PINS = {
    'ItemSet': 'c3cb162791b317fa323306f7cec8e04848bce6cf49f42039608c2b22560a99e2',
    'ItemSetSpell': 'd41d30ca156592761819d80bea3bb66c7ea2bcc43ecc71639e01c3a3ef9637ea',
    'ItemSparse': '8a26623b48a94a14cdd32a6597350d3e0700698e2480aa1cec6ab0ab7f06def3',
}


def read(name):
    raw = (ROOT / f'.dependencies/{name}-{BUILD}-zhCN.csv').read_bytes()
    assert hashlib.sha256(raw).hexdigest() == PINS[name], name
    rows = {}
    for row in csv.DictReader(io.StringIO(raw.decode('utf-8-sig'))):
        assert None not in row and all(v is not None for v in row.values())
        ident = int(row['ID'])
        assert ident > 0 and ident not in rows
        rows[ident] = row
    return rows


def build():
    raw, bonuses, sparse = read('ItemSet'), read('ItemSetSpell'), read('ItemSparse')
    sets, membership = {}, defaultdict(set)
    for ident, row in sorted(raw.items()):
        assert int(row['SetFlags']) == 0, 'unhandled set flags'
        sets[ident] = dict(name=row['Name_lang'], skill=int(row['RequiredSkill']),
                          rank=int(row['RequiredSkillRank']), bonuses=[])
        for key, value in row.items():
            if key.startswith('ItemID_') and int(value):
                membership[int(value)].add(ident)
    for row in sorted(bonuses.values(), key=lambda r: (int(r['Threshold']), int(r['ID']))):
        assert int(row['ChrSpecID']) == int(row['TraitSubTreeID']) == 0, 'unhandled bonus condition'
        ident, count, spell = int(row['ItemSetID']), int(row['Threshold']), int(row['SpellID'])
        assert ident in sets and count > 0 and spell > 0
        sets[ident]['bonuses'].append([count, spell])
    missing_bonuses = sorted(ident for ident, row in sets.items() if not row['bonuses'])
    # A present ItemSparse row is authoritative; absence is not a zero set ID.
    corrections = []
    for ident, row in sparse.items():
        sid = int(row['ItemSet'])
        assert not sid or sid in sets
        known = {sid} if sid else set()
        if membership.get(ident, set()) != known:
            corrections.append(dict(item=ident, listed=sorted(membership.get(ident, set())), itemSet=sid))
        if sid or ident in membership:
            membership[ident] = known
    conflicts = {ident: sorted(ids) for ident, ids in membership.items() if len(ids) > 1}
    items = {ident: next(iter(ids)) for ident, ids in membership.items() if len(ids) == 1}
    skills = sorted({row['skill'] for row in sets.values() if row['skill']})
    lines = ['local _,A=...', '-- Generated by tools/import_item_sets.py; see docs/ITEM_SET_AUDIT.json.',
             'A.ItemSets={version="1.60.1",build="70862",interface=16001,clientVerified=false,',
             '    skills={' + ','.join(f'[{n}]=true' for n in skills) + '},sets={']
    for ident, row in sorted(sets.items()):
        parts = ['name=' + json.dumps(row['name'], ensure_ascii=False)]
        if row['skill']:
            parts += [f"skill={row['skill']}", f"rank={row['rank']}"]
        if row['bonuses']:
            parts.append('bonuses={' + ','.join('{%d,%d}' % tuple(b) for b in row['bonuses']) + '}')
        lines.append('    [%d]={%s},' % (ident, ','.join(parts)))
    lines.append('},items={')
    lines += ['    [%d]=%d,' % (ident, sid) for ident, sid in sorted(items.items())]
    lines += ['},ambiguous={' + ','.join(f'[{n}]=true' for n in sorted(conflicts)) + '}}', '']
    report = dict(build=BUILD, interface=16001, clientVerified=False, sources=[
        dict(table=name, sha256=digest, rows=len(table),
             url=f'https://wago.tools/db2/{name}/csv?build={BUILD}&locale=zhCN')
        for (name, digest), table in zip(PINS.items(), [raw, bonuses, sparse])],
        counts=dict(sets=len(sets), bonuses=len(bonuses), items=len(items), ambiguousItems=len(conflicts)),
        missingBonusSetIds=missing_bonuses, conflicts=conflicts,
        sparseCorrections=sorted(corrections, key=lambda r: r['item']),
        membershipPolicy='Present ItemSparse.ItemSet wins, otherwise unique ItemSet.ItemID membership; conflicts remain unknown.',
        items=items)
    return '\n'.join(lines), report


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    lua, report = build()
    for name, value in {'Data/ItemSets.lua': lua,
                        'docs/ITEM_SET_AUDIT.json': json.dumps(report, ensure_ascii=False, indent=2)+'\n'}.items():
        path = ROOT / name
        if args.check:
            assert path.read_text() == value, name
        else:
            path.write_text(value)
    print(json.dumps(report['counts']), 'missing bonus sets:', report['missingBonusSetIds'])


if __name__ == '__main__':
    main()
