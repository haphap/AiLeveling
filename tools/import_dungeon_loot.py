"""Build the browse-only equipment index from the pinned sources in docs/SOURCES.json."""
import csv
import hashlib
import json
import re
import subprocess
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DEPS = ROOT / '.dependencies'
WINGS = {'EAST': '东区', 'NORTH': '北区', 'WEST': '西区', 'LOWER': '下层', 'UPPER': '上层',
         'ARMORY': '军械库', 'CATHEDRAL': '大教堂', 'GRAVEYARD': '墓地', 'LIBRARY': '图书馆',
         'MAIN_GATE': '正门', 'SERVICE_GATE': '后门'}


def table(name):
    with (DEPS / name).open() as stream:
        return {int(r['ID']): r for r in csv.DictReader(stream)}


def build():
    atlas = DEPS / 'DungeonQuestAtlas-1.04'
    assert hashlib.sha256((atlas / 'Bosses.lua').read_bytes()).hexdigest() == '176ec1d365d2bbcc7c17cf047ba8c39acea213e3501d8aa8de7886585e62d44f'
    assert hashlib.sha256((atlas / 'Dungeons.lua').read_bytes()).hexdigest() == '7c624b95afa6a344a0b48fc10517bf07d96a780ad914ba4f00d13f0b8ee14953'
    # Parse the pinned Lua tables with Lua itself, retaining only source identities and item IDs.
    extract = """
local data={}
assert(loadfile("Dungeons.lua"))("",data)
assert(loadfile("Bosses.lua"))("",data)
for _,d in ipairs(data.Dungeons) do
    for _,b in ipairs(data.Bosses[d.key] or {}) do
        local ids={}
        for _,drop in ipairs(b.loot or {}) do ids[#ids+1]=drop[1] end
        print(d.instanceID,d.part or "",b.name,b.npcID or "",b.kind or "",table.concat(ids,","))
    end
end"""
    raw = subprocess.check_output(['lua5.1', '-'], input=extract, text=True, cwd=atlas)
    types = table('Item-1.60.1.70938-zhCN.csv')
    gear = {i for i, r in types.items() if r['ClassID'] in ('2', '4') and int(r['InventoryType']) > 0}
    en = table('DungeonEncounter-1.60.1.70862.csv')
    zh = table('DungeonEncounter-1.60.1.70862-zhCN.csv')
    census = json.loads((ROOT / 'docs/DUNGEON_COVERAGE.json').read_text())
    maps = {r['mapId'] for r in census['maps'] + census['supplementalMaps'] if r['classification'] == 'party'}
    by_map = defaultdict(dict)

    def key(name):
        return re.sub('[^a-z0-9]', '', name.lower())

    for line in raw.splitlines():
        instance, wing, name, npc, kind, ids = line.split('\t')
        items = {int(i) for i in ids.split(',') if i} & gear
        if not items:
            continue
        zone = int(instance)
        assert zone in maps
        # The original Hall of Thanes guide uses the beta name of Infurnus.
        boss = 'infurnus' if zone == 3065 and name == 'Magmatus' else key(name)
        group_key = (wing, boss)
        group = by_map[zone].setdefault(group_key, dict(name=name, npc=npc, items=set(), seen=set(), beta=set(), wing=wing))
        if kind == 'trash':
            group['name'] = '普通敌人'
        group['items'].update(items)

    # Match by instance as names may be shared across maps. Prefer Forever encounter names.
    for encounter, row in en.items():
        zone = int(row['MapID'])
        for (_, boss), group in by_map.get(zone, {}).items():
            if boss == key(row['Name_lang']) and encounter in zh:
                group['name'] = zh[encounter]['Name_lang']
    sources = ['1.60.1.' + str(build) for build in (70790, 70862, 70888, 70938)]
    sources += ['wow_classic_beta/1.60.1.70338', 'wow_classic_beta/1.60.1.70374']
    for source_dir in sources:
        path = DEPS / 'eg-link-06b4cc7b' / source_dir / 'loot.json'
        for source, roll in json.loads(path.read_text())['rolls'].items():
            encounter = int(source.split('|')[0].removeprefix('encounter:'))
            row = en.get(encounter)
            if not row or int(row['MapID']) not in maps or roll['kills'] <= 0:
                continue
            items = {int(i) for i, obs in roll['items'].items() if obs['drops'] > 0} & gear
            if not items:
                continue
            groups = by_map[int(row['MapID'])]
            name = key(row['Name_lang'])
            group = next((g for (_, b), g in groups.items() if b == name), None)
            if group is None:
                group = groups['', name] = dict(name=zh[encounter]['Name_lang'], npc='', wing='', items=set(), seen=set(), beta=set())
            group['items'].update(items)
            group['beta' if source_dir.startswith('wow_classic_beta/') else 'seen'].update(items)

    lines = ['-- Generated by tools/import_dungeon_loot.py. Pirson (MIT) and Efficient Games (CC BY 4.0).',
             '-- See docs/SOURCES.json and the accompanying licenses.', 'local _,A=...', 'A.DungeonCatalog.dropsByInstance={']
    for zone, groups in sorted(by_map.items()):
        lines.append(f'    [{zone}]={{')
        for g in groups.values():
            fields = ['name=' + json.dumps(g['name'], ensure_ascii=False)]
            if g['npc']:
                fields.append('npc=' + g['npc'])
            if g['wing']:
                fields.append('wing=' + json.dumps(WINGS[g['wing']], ensure_ascii=False))
            fields.append('items={' + ','.join(map(str, sorted(g['items']))) + '}')
            for status, ids in [('observed', g['seen']), ('beta', g['beta'] - g['seen'])]:
                if ids:
                    fields.append(status + '={' + ','.join(f'[{i}]=true' for i in sorted(ids)) + '}')
            lines.append('        {' + ','.join(fields) + '},')
        lines.append('    },')
    (ROOT / 'Data/DungeonLoot.lua').write_text('\n'.join(lines + ['}', '']))


if __name__ == '__main__':
    build()
