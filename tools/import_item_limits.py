#!/usr/bin/env python3
"""Import positive per-item possession limits from the pinned client table."""
import argparse,csv,hashlib,io,json
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
SOURCE='.dependencies/ItemSparse-1.60.1.70862-zhCN.csv'
DIGEST='8a26623b48a94a14cdd32a6597350d3e0700698e2480aa1cec6ab0ab7f06def3'
def build():
    raw=(ROOT/SOURCE).read_bytes()
    assert hashlib.sha256(raw).hexdigest()==DIGEST
    rows=list(csv.DictReader(io.StringIO(raw.decode('utf-8-sig'))))
    limits={int(r['ID']):int(r['MaxCount']) for r in rows if int(r['MaxCount'])>0}
    assert len({r['ID'] for r in rows})==len(rows)
    lua=['local _,A=...', '-- Generated by tools/import_item_limits.py; see docs/ITEM_LIMIT_AUDIT.json.',
         'A.ItemLimits={version="1.60.1",build="70862",interface=16001,counts={']
    lua += [f'    [{id}]={count},' for id,count in sorted(limits.items())]
    lua += ['}}','']
    report=dict(build='1.60.1.70862',source=SOURCE,sha256=DIGEST,clientVerified=False,
        url='https://wago.tools/db2/ItemSparse/csv?build=1.60.1.70862&locale=zhCN',
        semantics='https://trinitycore.info/database/335/world/item_template#maxcount',
        sourceRows=len(rows),positiveLimits=len(limits),
        scope='Positive MaxCount only, distinct from per-slot Stackable and equipped-item category limits. Does not infer quest requirement counts. Exact client build required.',
        limits=['Bank-held copies and per-category possession limits are not modeled.',
                'Quest-only drop eligibility may impose additional acquisition limits.'])
    return {'Data/ItemLimits.lua':'\n'.join(lua),'docs/ITEM_LIMIT_AUDIT.json':json.dumps(report,ensure_ascii=False,indent=2)+'\n'}
if __name__=='__main__':
    parser=argparse.ArgumentParser();parser.add_argument('--check',action='store_true');args=parser.parse_args()
    for name,value in build().items():
        if args.check:assert (ROOT/name).read_text()==value,name
        else:(ROOT/name).write_text(value)
    print('Item possession limits checked' if args.check else 'Item possession limits generated')
